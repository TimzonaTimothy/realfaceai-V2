# ── Maintenance mode ──────────────────────────────────────────────────────────
#
# Option A — Immediate toggle (turn on/off right now):
#   MAINTENANCE_MODE=true          → active immediately
#   MAINTENANCE_MODE=false         → off (default)
#
# Option B — Scheduled window (set in .env, times are UTC ISO 8601):
#   MAINTENANCE_SCHEDULED_START=2026-05-28T02:00:00+00:00
#   MAINTENANCE_SCHEDULED_END=2026-05-28T04:00:00+00:00
#
# Both options can be combined:
#   Set MAINTENANCE_MODE=false and set the scheduled window — the middleware
#   will automatically activate during the window and deactivate after.
#
# To turn maintenance ON immediately for an unplanned outage:
#   1. Set MAINTENANCE_MODE=true in .env
#   2. Restart gunicorn: sudo systemctl restart gunicorn
#
# To turn maintenance OFF:
#   1. Set MAINTENANCE_MODE=false in .env
#   2. Restart gunicorn
#
