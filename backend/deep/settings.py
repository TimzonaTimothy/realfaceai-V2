# Scheduled window — parsed from ISO 8601 strings in .env
# e.g. MAINTENANCE_SCHEDULED_START=2026-05-28T02:00:00+00:00
def _parse_dt(key):
    val = env.str(key, default='')
    if not val:
        return None
    try:
        import dateutil.parser
        from django.utils import timezone as _tz
        dt = dateutil.parser.isoparse(val)
        # Make timezone-aware (assume UTC if no tzinfo)
        if dt.tzinfo is None:
            from django.utils.timezone import make_aware
            from datetime import timezone as _pytz
            dt = dt.replace(tzinfo=_pytz.utc)
        return dt
    except Exception:
        return None

MAINTENANCE_SCHEDULED_START = _parse_dt('MAINTENANCE_SCHEDULED_START')
